package backend.yourtrip.global.ai.candidate;

import java.util.Optional;
import lombok.Getter;
import lombok.RequiredArgsConstructor;

/**
 * 스타일 속성의 <b>닫힌 태그 집합</b>. 후보 공급과 지식 신호 층이 공유하는 유일한 어휘다.
 *
 * <p>자유 텍스트로 두지 않는 이유는 설계가 명시한 그대로다 — 열어두면 "요약 단계 자체가 새로운
 * 환각 지점이 되고 테스트도 불가능해진다".
 *
 * <p><b>어휘를 합집합으로 둔 이유.</b> 설계는 4-3(키워드→traits 사전)과 4-9(`cat3`→스타일 태그)가
 * <i>같은 traits 어휘</i>를 쓴다고 못박았는데, 두 표를 실제로 대조해 보니 어긋나 있었다 — 4층 traits
 * 26개에 4-9가 쓰는 {@code 자연}·{@code 역사}·{@code 문화}·{@code 액티비티}·{@code 실내}가 없다.
 * 어휘를 둘로 나누면 9단계 4층을 켤 때 매핑 테이블을 두 벌 유지해야 하므로, <b>합집합 31개</b>를
 * 한 enum으로 두어 설계의 그 문장이 실제로 성립하게 만든다.
 *
 * <h2>{@code searchTerm} — 태그 이름과 검색어를 나누는 이유</h2>
 * 태그 이름은 속성을 가리키는 라벨이고, 검색어는 네이버 지역검색에 실제로 실리는 문자열이다. 둘은
 * 자주 다르다 — {@code QUIET}의 라벨은 "조용함"이지만 쿼리에는 {@code "조용한"}으로 들어가야
 * 자연스럽고, {@code PARKING_AVAILABLE}은 "주차가능"이 아니라 {@code "주차"}가 낫다(4-2 실측에서
 * {@code "공주 주차 맛집"}이 신규 후보 4/4를 줬다).
 *
 * <p><b>{@code searchTerm}이 없는 태그가 8개 있고, 이유는 셋으로 갈린다.</b> 비워 두면
 * {@link StyleModifierDictionary}가 구조적으로 그것을 고르지 못한다.
 *
 * <ol>
 *   <li><b>감점으로 지금 일한다</b> — {@code 주차난}·{@code 웨이팅}·{@code 시끌벅적}. 사용자가
 *       피하고 싶다고 표시한 축이라 쿼리로 부를 일이 없다. <b>지우면 회피 규칙이 사라진다</b></li>
 *   <li><b>가점 목록의 자리를 지킨다</b> — {@code 통창}·{@code 아늑함}. 실측에서 통하는 표기를
 *       못 찾아 출력에서 걸러지지만, 설계 표의 우선순위를 보존한다. 나중에 표기를 찾으면
 *       {@code searchTerm} 한 줄만 채우면 원래 순위가 되살아난다</li>
 *   <li><b>어휘 예약 — 사전에서 쓰이지 않는다</b> — {@code 예약필수}·{@code 보통}·{@code 브레이크타임}.
 *       9단계 4층이 블로그 스니펫에서 추출할 속성이며 <b>지금은 어디서도 참조되지 않는다.</b>
 *       9단계가 조건부라 영영 안 올 수도 있지만, 설계 문서의 traits 표를 그대로 옮긴 것이라
 *       지우면 코드와 설계가 어긋난다</li>
 * </ol>
 *
 * <h2>업종은 이 어휘에 넣지 않는다</h2>
 * {@code 소품샵}을 태그로 추가했다가 되돌렸다. 실측에서 후보를 잘 끌어왔지만(3개 지역 12건),
 * <b>이 어휘는 "장소가 어떤 속성을 갖는가"를 담고 업종은 {@code SlotType}이 담는다.</b> 둘을
 * 섞으면 층이 무너진다.
 *
 * <p>실측이 그 이유를 그대로 보여줬다 — {@code "강릉 소품샵 맛집"}이 {@code "강릉 소품샵 카페"}와
 * <b>완전히 같은 결과</b>를 돌려줬다. 스타일 수식어는 "어떤 성격의 X"로 X를 좁히는데 {@code 소품샵}은
 * X 자리에 오는 업종이라, 슬롯 힌트({@code 맛집}·{@code 카페})와 경쟁해 그것을 밀어낸 것이다.
 * 그대로 뒀다면 소품샵이 식사 후보로 들어왔을 것이다.
 *
 * <h2>검색어 표기는 전량 실측했다</h2>
 * 26개를 각자 겨냥하는 슬롯(카페·맛집·관광명소)으로 던져 <b>결과 건수 · 기본 쿼리 대비 신규 ·
 * 상호명 포함률</b>을 쟀다(4-3 보강, 총 44회 호출). 22개가 신규 후보를 실제로 끌어왔고,
 * <b>4개는 죽은 표기라 조정하거나 비웠다.</b>
 *
 * <ul>
 *   <li>{@code 도보} → {@code 역근처} (0건 → 신규 5/5)</li>
 *   <li>{@code 한적한} → {@code 한적} (0건 → 1건, 표본이 얇다)</li>
 *   <li>{@code 통창} — 통유리·창가까지 셋 다 0건이라 <b>비웠다</b></li>
 *   <li>{@code 시끌벅적한} — 번화가 0건, 핫플은 기본 쿼리와 전부 겹쳐 <b>비웠다</b></li>
 * </ul>
 *
 * <p><b>상호명 포함률이 거의 0이었다는 것이 중요하다.</b> 신규 후보의 상호명에 그 단어가 들어 있지
 * 않다는 뜻이므로, 네이버가 이름이 아니라 <b>속성</b>을 매칭한다는 근거가 된다 — 스타일 축을
 * retrieval에 두는 이 설계의 전제가 여기서 확인됐다.
 *
 * <p><b>남는 한계 — 표기의 유효성은 슬롯에 따라 다르다.</b> {@code 뷰맛집}은 카페에서 신규 5/5인데
 * 관광명소에서는 0건이다. 지금은 태그마다 표기 하나만 두므로 그런 조합은 빈 결과로 fail-open 된다
 * (합집합이라 풀이 줄지는 않는다). 슬롯별 표기가 필요한지는 5-9에서 판단한다.
 */
@RequiredArgsConstructor
public enum StyleTag {

    // ── 뷰·분위기 ────────────────────────────────────────────────────────────
    NIGHT_VIEW("야경", "야경"),
    GREAT_VIEW("뷰맛집", "뷰맛집"),
    ROOFTOP("루프탑", "루프탑"),
    /** <b>검색어 없음</b> — 통창·통유리·창가 셋 다 0건이었다(4-3 보강 실측). */
    PANORAMIC_WINDOW("통창", null),
    HANOK("한옥", "한옥"),
    RETRO("레트로", "레트로"),
    SPACIOUS("넓음", "넓은"),
    /**
     * <b>검색어 없음</b> — 아늑한·아늑·아늑함 전부 3개 지역에서 0~1건이었다(3차 실측).
     * 결과가 나오는 표기가 하나 있었지만({@code 소품샵}, 12건) <b>의미가 다르다</b> — 검색 결과가
     * 나온다고 채택하면 태그가 가리키는 속성과 실제로 끌어온 후보가 어긋난다.
     */
    COZY("아늑함", null),
    QUIET("조용함", "조용한"),
    /**
     * <b>검색어 없음</b> — 시끌벅적한·번화가는 0건, 핫플은 기본 쿼리와 전부 겹쳤다(4-3 보강 실측).
     *
     * <p><b>그래도 지금 일하고 있다</b> — {@code FRIENDS}의 가점이자 {@code COUPLE}·{@code HEALING}의
     * 감점이다. 지우면 "연인·힐링 요청에서 시끌벅적한 곳을 피한다"는 규칙까지 함께 사라진다.
     */
    LIVELY("시끌벅적", null),

    // ── 접근성 ───────────────────────────────────────────────────────────────
    NEAR_STATION("역세권", "역세권"),
    /** {@code 도보}·{@code 도보5분}은 0건이라 {@code 역근처}로 바꿨다(신규 5/5). */
    WALKABLE("도보접근", "역근처"),
    PARKING_AVAILABLE("주차가능", "주차"),
    /** <b>감점으로 쓰인다</b> — {@code FAMILY}·{@code CAR}가 피한다. 피하고 싶은 속성이라 쿼리로 부르지 않는다. */
    PARKING_DIFFICULT("주차난", null),

    // ── 혼잡 ─────────────────────────────────────────────────────────────────
    /** <b>감점으로 쓰인다</b> — {@code FAMILY}·{@code HEALING}이 피한다. */
    LONG_WAIT("웨이팅", null),
    /**
     * <b>어휘 예약 — 사전에서 쓰이지 않는다.</b> 가점에도 감점에도 등장하지 않으며, 9단계 4층이
     * 블로그 스니펫에서 "예약 필수"를 사실로 추출할 때 쓸 자리다. 9단계는 조건부라 영영 안 올 수도
     * 있지만, 설계 문서의 traits 표를 그대로 옮긴 것이라 지우면 코드와 설계가 어긋난다
     * ({@code SlotType.popularityWeight}가 같은 상태다).
     */
    RESERVATION_REQUIRED("예약필수", null),
    /**
     * 한적한·한적·한적함·조용한골목은 3개 지역 신규 합계가 0~1건이라 전부 탈락했고,
     * {@code 숨은}만 6건을 끌어왔다(3차 실측). <b>직역이 아니라 대용어다</b> — "숨은 카페"는
     * 한적함을 함의하는 관용 표현이라 채택했지만, 완전히 같은 뜻은 아니다.
     */
    UNCROWDED("한적함", "숨은"),

    // ── 동반 ─────────────────────────────────────────────────────────────────
    PET_FRIENDLY("반려동물동반", "애견동반"),
    KID_FRIENDLY("아이동반", "아이동반"),
    GROUP_FRIENDLY("단체가능", "단체"),

    // ── 가격 ─────────────────────────────────────────────────────────────────
    CHEAP("저렴", "가성비"),
    /**
     * <b>어휘 예약 — 사전에서 쓰이지 않는다.</b> 검색어로도 무의미하다("보통 카페"를 찾는 사람은
     * 없다). {@code NORMAL}(평균예산) 키워드의 매핑을 비운 것과 짝을 이룬다.
     */
    MODERATE("보통", null),
    /** 고급 7 · 고급스러운 10 · 파인다이닝 13 · <b>프리미엄 15</b>(3차 실측, 3개 지역 신규 합계). */
    EXPENSIVE("고가", "프리미엄"),

    // ── 시간 ─────────────────────────────────────────────────────────────────
    MORNING_OPEN("아침영업", "아침"),
    LATE_NIGHT("야간영업", "야간"),
    /** <b>어휘 예약 — 사전에서 쓰이지 않는다.</b> 9단계 4층이 영업시간 속성을 추출할 때 쓸 자리다. */
    BREAK_TIME("브레이크타임", null),

    // ── 4-9(`cat3` 매핑)가 요구하는 확장 어휘 ────────────────────────────────
    NATURE("자연", "자연"),
    HISTORY("역사", "역사"),
    CULTURE("문화", "문화"),
    ACTIVITY("액티비티", "체험"),
    INDOOR("실내", "실내");

    /** 사람이 읽는 태그 이름. 설계 문서의 traits 표기와 1:1로 맞춘다. */
    @Getter
    private final String label;

    /**
     * 지역검색 쿼리에 실리는 문자열. 없으면 modifier로 쓰이지 않는다.
     *
     * <p><b>이 필드에는 Lombok {@code @Getter}를 붙이지 않는다.</b> nullable 이라 raw 접근자를
     * 열어두면 호출부가 그것을 잡아 NPE를 만든다 — 접근은 {@link #searchTerm()}(Optional) 하나로만
     * 한다.
     */
    private final String searchTerm;

    /** modifier 쿼리에 쓸 수 있는 태그인가. */
    public boolean isSearchable() {
        return searchTerm != null;
    }

    public Optional<String> searchTerm() {
        return Optional.ofNullable(searchTerm);
    }
}
