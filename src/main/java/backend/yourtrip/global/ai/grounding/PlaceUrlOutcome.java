package backend.yourtrip.global.ai.grounding;

/**
 * URL 보강 시도 하나의 결말 — 메트릭 {@code ai.place.url{result=...}}의 태그다 (ROADMAP 5-10).
 *
 * <p>{@link GroundingOutcome}과 값이 겹치지만 <b>같은 enum을 쓰지 않는다.</b> 두 단계가 다룰 수
 * 있는 사건의 집합이 다르다 — 그라운딩에는 {@link #TOO_FAR}가 없고 URL 보강에는 업종 제약이 없다.
 * 하나로 합치면 어느 쪽에서도 발생할 수 없는 값이 태그 목록에 남아 대시보드를 읽는 사람이
 * "왜 이건 항상 0인가"를 되짚게 된다. 4-5가 "실패 사유 어휘는 공유하고 결과 타입은 공유하지
 * 않는다"고 정한 것과 같은 결이다.
 */
public enum PlaceUrlOutcome {

    /** 이름 게이트와 거리 검증을 모두 통과해 URL을 붙였다. */
    HIT,

    /** 이름이 맞지 않는다. 네이버↔카카오 상호명 표기 차이가 잦으면 여기가 는다. */
    NAME_MISMATCH,

    /** 카카오에 아무것도 없다. */
    NO_RESULT,

    /**
     * 이름은 맞는데 좌표가 300m를 넘는다 — <b>같은 상호명의 다른 지점</b>이다.
     *
     * <p>좌표를 두 소스에서 갖게 된 덕에 공짜로 생긴 교차 검증이고, 이 값이 잦으면 전국구
     * 프랜차이즈·동명 업소 문제라는 뜻이다.
     */
    TOO_FAR,

    /** 검색은 맞췄는데 응답에 좌표가 없어 거리 검증을 할 수 없다. */
    NO_COORDINATE,

    /** 호출 자체가 실패했다. */
    FAILED,

    /** 예산이 부족해 아예 부르지 않았다. 데드라인 임박 시 이 단계는 통째로 건너뛴다. */
    SKIPPED
}
