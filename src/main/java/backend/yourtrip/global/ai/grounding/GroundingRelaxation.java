package backend.yourtrip.global.ai.grounding;

/**
 * 검증의 결말을 <b>우리가 뒤집은</b> 사유 — 메트릭 {@code ai.grounding.relaxed{reason=...}}의
 * 태그다 (이슈 #147).
 *
 * <h2>{@link GroundingOutcome}을 재활용하지 않는 이유</h2>
 * 저쪽은 <b>검증이 무엇이라고 답했는가</b>를 세고, 이쪽은 <b>그 답을 우리가 몇 번 뒤집었는가</b>를
 * 센다. 뭉치면 5-3의 업종 제약이 실제로 무엇을 걸렀는지 영영 못 재게 되고, 무엇보다
 * <b>"이 완화가 환각을 몇 건 들였는가"</b>를 나중에 되짚을 수 없다 — 완화를 넣는 대가로 반드시
 * 남겨야 하는 축이 이것이다.
 *
 * <p><b>값이 하나뿐이지만 enum으로 둔다.</b> 태그 문자열을 그냥 넘기면 오타 하나가 조용히 새
 * 시계열을 만들고, 0 등록({@code AiCourseMetrics})이 무엇을 등록해야 하는지도 알 수 없다.
 *
 * <p><b>{@code source} 태그를 두지 않는다.</b> 카카오 검증 경로에서만 나오므로 출처가 항상
 * {@code SUGGESTED}다. 상수인 축을 태그로 두면 대시보드를 읽는 사람이 "왜 나머지는 항상 0인가"를
 * 되짚게 된다(5-6이 {@code PlaceUrlOutcome}을 따로 만든 것과 같은 판단).
 */
public enum GroundingRelaxation {

    /**
     * 업종이 슬롯과 어긋났지만 <b>슬롯이 전멸해</b> 최후 구제로 실렸다.
     *
     * <p><b>{@code ai.grounding.match}와 발화 시점이 다르다.</b> 저쪽은 후보를 판정하는 즉시 오르지만
     * 이 값은 슬롯을 다 훑은 뒤에야 오른다 — 슬롯 전멸이라는 조건 자체가 이 구제의 정의라, 중간에는
     * 구제인지 아닌지 알 수가 없다. 중복 제거까지 통과해 <b>실제로 코스에 실린 건만</b> 센다.
     */
    CATEGORY_LAST_RESORT
}
